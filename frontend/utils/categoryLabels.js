const SUPPORTED = ['fr', 'en', 'es', 'pt'];

export const getCategoryLabel = (categoryId, language = 'en') => {
  const normalizedId = String(categoryId || '').trim();
  if (!normalizedId) return '';

  const safeLanguage = SUPPORTED.includes(language) ? language : 'en';
  return (
    CATEGORY_LABELS?.[safeLanguage]?.[normalizedId] ||
    CATEGORY_LABELS?.en?.[normalizedId] ||
    normalizedId
  );
};

